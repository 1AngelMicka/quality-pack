// Static release checks: what can be read in the project without a device.

const read = (p) => { try { return readFileSync(p, "utf8"); } catch { return null; } };
function find(root, names, { max = 4000, skip = /^(node_modules|\.git|build|Pods|\.gradle|dist|\.expo|DerivedData)$/ } = {}) {
  const out = [];
  let seen = 0;
  const walk = (dir, depth) => {
    if (depth > 7 || seen > max) return;
    let entries = [];
    try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      seen++;
      if (e.isDirectory()) { if (!skip.test(e.name)) walk(join(dir, e.name), depth + 1); }
      else if (names.some((n) => (n instanceof RegExp ? n.test(e.name) : n === e.name))) out.push(join(dir, e.name));
    }
  };
  walk(root, 0);
  return out;
}

async function fetchHead(url) {
  try {
    const res = await fetch(url, { redirect: "manual", signal: AbortSignal.timeout(15000) });
    const text = await res.text().catch(() => "");
    let json = false;
    try { JSON.parse(text); json = true; } catch { /* not JSON */ }
    return { status: res.status, json, redirect: res.status >= 300 && res.status < 400 ? res.headers.get("location") : null };
  } catch (e) { return { error: String(e.cause?.code || e.message).slice(0, 120) }; }
}

export async function mobileChecks(project, root) {
  const m = project?.mobile || {};
  const rel = (p) => relative(root, p).split("\\").join("/");
  const checks = {};
  const add = (id, level, ok, value, rule, where) => { checks[id] = { level, ok, value, rule, ...(where ? { where } : {}) }; };
  const pkg = JSON.parse(read(join(root, "package.json")) || "{}");
  const deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };
  const approach = m.approach || (deps.expo ? "expo" : deps["react-native"] ? "react-native" : Object.keys(deps).some((d) => d.startsWith("@capacitor/")) ? "capacitor"
    : existsSync(join(root, "pubspec.yaml")) ? "flutter" : existsSync(join(root, "src-tauri")) ? "tauri" : "unknown");

  // --- Android ---
  const gradles = find(root, ["build.gradle", "build.gradle.kts"]).filter((f) => /[\\/]app[\\/]build\.gradle/.test(f));
  const manifests = find(root, ["AndroidManifest.xml"]).filter((f) => /[\\/]src[\\/]main[\\/]/.test(f));
  const appJson = JSON.parse(read(join(root, "app.json")) || "{}");
  const expo = appJson.expo || null;
  let target = null, targetWhere = null;
  for (const g of gradles) {
    const t = /targetSdk(?:Version)?\s*[=(]?\s*(\d+)/.exec(read(g) || "");
    if (t) { target = Number(t[1]); targetWhere = rel(g); break; }
  }
  if (target == null) {
    const props = expo?.plugins?.find?.((p) => Array.isArray(p) && p[0] === "expo-build-properties")?.[1]?.android?.targetSdkVersion;
    if (props) { target = Number(props); targetWhere = "app.json (expo-build-properties)"; }
  }
  if (target != null) add("android_target_api", "must", target >= PLAY_TARGET_API, `targetSdk ${target}`, `Google Play requires new apps and updates to target API ${PLAY_TARGET_API} or higher`, targetWhere);
  else if (gradles.length) add("android_target_api", "should", true, "targetSdk comes from a variable or the framework: check the built app (`aapt dump badging app.apk`)", `Google Play requires target API ${PLAY_TARGET_API} or higher`);
  for (const f of manifests) {
    const x = read(f) || "";
    if (/android:debuggable\s*=\s*"true"/.test(x)) add("android_debuggable", "must", false, 'android:debuggable="true" in the main manifest', "a release build is never debuggable", rel(f));
    if (/android:usesCleartextTraffic\s*=\s*"true"/.test(x)) add("android_cleartext", "must", false, 'usesCleartextTraffic="true"', "the app talks over TLS only: no cleartext traffic allowed in the main manifest", rel(f));
    const exported = (x.match(/<(activity|service|receiver|provider)\b[^>]*android:exported\s*=\s*"true"[^>]*>/g) || []).length;
    const backup = /android:allowBackup\s*=\s*"true"/.test(x) && !/android:(dataExtractionRules|fullBackupContent)=/.test(x);
    if (backup) add("android_backup", "should", false, 'allowBackup="true" with no backup rules', "session tokens and private data are excluded from device backups (backup rules, or allowBackup=false)", rel(f));
    if (exported > 3) add("android_exported", "should", false, `${exported} exported components`, "only the components other apps must reach are exported; each one validates what it receives", rel(f));
  }
  for (const f of find(root, ["network_security_config.xml"])) {
    if (/cleartextTrafficPermitted\s*=\s*"true"/.test(read(f) || "") && !/[\\/]debug[\\/]/.test(f)) add("android_cleartext", "must", false, "cleartextTrafficPermitted in the network security config", "the app talks over TLS only (cleartext only in a debug-only config)", rel(f));
  }
  if (manifests.length && !checks.android_debuggable) add("android_debuggable", "must", true, "not set in the main manifest (release builds are not debuggable by default)", "a release build is never debuggable");
  if (manifests.length && !checks.android_cleartext) add("android_cleartext", "must", true, "no cleartext exception found", "the app talks over TLS only");

  // --- iOS ---
  const plists = find(root, ["Info.plist"]).filter((f) => !/Pods|Tests|\.framework/.test(f));
  const iosProject = plists.length > 0 || existsSync(join(root, "ios"));
  if (iosProject) {
    const manifestsIos = find(root, ["PrivacyInfo.xcprivacy"]);
    const expoPrivacy = !!expo?.ios?.privacyManifests;
    add("ios_privacy_manifest", "must", manifestsIos.length > 0 || expoPrivacy, manifestsIos.length ? rel(manifestsIos[0]) : expoPrivacy ? "app.json › expo.ios.privacyManifests" : "no PrivacyInfo.xcprivacy",
      "the app ships a privacy manifest declaring the required-reason APIs it uses (App Store Connect refuses builds without it)");
    for (const f of plists) {
      const x = read(f) || "";
      if (/<key>NSAllowsArbitraryLoads<\/key>\s*<true\/>/.test(x)) add("ios_ats", "must", false, "NSAllowsArbitraryLoads is true", "App Transport Security stays on: no blanket exception for insecure connections", rel(f));
      const usage = [...x.matchAll(/<key>(NS\w+UsageDescription)<\/key>\s*<string>([^<]*)<\/string>/g)];
      const vague = usage.filter(([, , text]) => text.trim().length < 20).map(([, k]) => k);
      if (usage.length) add("ios_permission_texts", "must", vague.length === 0, `${usage.length} permission text(s), ${vague.length} too short to explain why`, "each permission text says what the app does with the access, in the user's words (App Review 5.1.1)", vague.length ? `${rel(f)}: ${vague.join(", ")}` : undefined);
    }
    if (plists.length && !checks.ios_ats) add("ios_ats", "must", true, "no blanket exception", "App Transport Security stays on");
  }

  // --- WebView shells (Capacitor) ---
  for (const f of find(root, [/^capacitor\.config\.(json|ts|js|mjs)$/])) {
    const x = read(f) || "";
    const wild = /allowNavigation\s*["']?\s*:\s*\[[^\]]*["']\*["']/.test(x);
    const clear = /cleartext\s*["']?\s*:\s*true/.test(x);
    const live = /["']?url["']?\s*:\s*["']http/.test(x);
    add("webview_navigation", "must", !wild && !clear, wild ? 'allowNavigation contains "*"' : clear ? "server.cleartext is true" : "no wildcard navigation, no cleartext", "the WebView only loads the app's own origins over HTTPS (the native bridge is exposed to every page it loads)", rel(f));
    if (live) add("webview_live_url", "should", false, "server.url points to a live site", "a store build loads its bundled files: server.url is for development only (a bare website wrapper is refused by App Review 4.2)", rel(f));
  }

  // --- On the web site: link files and account deletion ---
  const host = m.links_host || (() => { try { return new URL(project?.urls?.production).origin; } catch { return null; } })();
  if (host) {
    const origin = /^https?:/.test(host) ? host.replace(/\/$/, "") : `https://${host}`;
    const al = await fetchHead(`${origin}/.well-known/assetlinks.json`);
    const aasa = await fetchHead(`${origin}/.well-known/apple-app-site-association`);
    const say = (r) => r.error ? r.error : r.redirect ? `redirects to ${r.redirect}` : `HTTP ${r.status}${r.status === 200 && !r.json ? ", not JSON" : ""}`;
    if (manifests.length || approach !== "unknown") add("android_app_links", "should", al.status === 200 && al.json, say(al), "links to the site open the app: /.well-known/assetlinks.json answers 200 with JSON and no redirect", `${origin}/.well-known/assetlinks.json`);
    if (iosProject || approach !== "unknown") add("ios_universal_links", "should", aasa.status === 200 && aasa.json, say(aasa), "links to the site open the app: /.well-known/apple-app-site-association answers 200 with JSON and no redirect", `${origin}/.well-known/apple-app-site-association`);
  }
  if (m.account_deletion_url) {
    const d = await fetchHead(m.account_deletion_url);
    add("account_deletion_page", "must", d.status === 200, d.error || `HTTP ${d.status}`, "a public web page lets a user ask for account deletion without reinstalling the app (Google Play), besides the path inside the app (Apple 5.1.1(v), Google Play)", m.account_deletion_url);
  } else if (project?.flags?.includes?.("has_auth")) {
    add("account_deletion_page", "must", false, "mobile.account_deletion_url is not declared", "a public web page lets a user ask for account deletion without reinstalling the app (Google Play), besides the path inside the app");
  }
  const must = Object.entries(checks).filter(([, c]) => c.level === "must" && !c.ok).map(([k]) => k);
  const should = Object.entries(checks).filter(([, c]) => c.level === "should" && !c.ok).map(([k]) => k);
  return { approach, platforms: { android: gradles.length > 0 || manifests.length > 0, ios: iosProject }, summary: { checks: Object.keys(checks).length, must_failed: must, should_failed: should }, checks,
    not_covered: ["store forms (Data safety, privacy labels, age rating) match the SDKs really shipped", "payment rules for the chosen storefronts (in-app purchase or not)", "16 KB page alignment of native libraries (check the built APK)", "behaviour on a device: keyboard, safe areas, back, large text, offline (mobile flows)"],
    note: "Read from the project files" + (existsSync(join(root, "android")) || existsSync(join(root, "ios")) ? "." : ". No android/ or ios/ folder found: with Expo managed builds, run `npx expo prebuild` in a copy to check the generated projects.") };
}
