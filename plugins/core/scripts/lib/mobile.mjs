// Installed mobile apps (iOS, Android). Two things a browser cannot do:
//  - play the key tasks on an emulator, simulator or device, with Maestro (Apache-2.0, free on your own
//    devices; its paid cloud is never used). Tasks are declared in .quality/project.json › mobile.flows with
//    a small step vocabulary, and turned into Maestro flows;
//  - read the project for what blocks a store release or weakens the app: target API level, debuggable or
//    cleartext builds, missing privacy manifest, wide-open WebView, link files and deletion page on the site.
// iOS builds and simulators need macOS: on Windows and Linux only Android can be played.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

export const MOBILE_STEPS = ["launch", "tap", "long_press", "type", "erase", "expect", "expect_gone", "wait_for", "screenshot", "back", "scroll_to", "swipe", "open_link", "offline", "dark", "hide_keyboard", "press"];
const COUNTED = new Set(["tap", "long_press", "type", "swipe", "press"]);
// Google Play: new apps and updates must target this API level (Android 16) since 2026-08-31.
export const PLAY_TARGET_API = 36;

const q = (s) => JSON.stringify(String(s)); // YAML double-quoted scalar
const sel = (v) => typeof v === "string" ? q(v) : null;

// One selector, inline for a text, as a block for an id or a richer match.
function target(v, indent = "    ") {
  if (typeof v === "string") return ` ${q(v)}`;
  const lines = [];
  for (const k of ["id", "text", "index", "below", "above", "childOf"]) if (v?.[k] != null) lines.push(`${indent}${k}: ${typeof v[k] === "number" ? v[k] : q(v[k])}`);
  return `\n${lines.join("\n")}`;
}

export function validateMobile(project) {
  const errors = [];
  const m = project?.mobile;
  if (m == null) return { flows: [], errors, mobile: null };
  if (typeof m !== "object" || Array.isArray(m)) return { flows: [], errors: ["mobile must be an object"], mobile: null };
  if (m.flows != null && !Array.isArray(m.flows)) errors.push("mobile.flows must be a list");
  const flows = [];
  const ids = new Set();
  for (const [i, f] of (Array.isArray(m.flows) ? m.flows : []).entries()) {
    const where = `mobile.flows[${i}]${f?.id ? ` (${f.id})` : ""}`;
    if (!f || typeof f !== "object") { errors.push(`${where}: must be an object`); continue; }
    if (!f.id || !/^[a-z0-9][a-z0-9-]*$/.test(f.id)) errors.push(`${where}: id must be lower-case letters, digits and dashes`);
    if (ids.has(f.id)) errors.push(`${where}: duplicate id`);
    ids.add(f.id);
    if (!f.name) errors.push(`${where}: name is required (the task in the user's words)`);
    if (!Array.isArray(f.steps) || !f.steps.length) { errors.push(`${where}: steps must be a non-empty list`); continue; }
    f.steps.forEach((s, j) => {
      const keys = Object.keys(s || {}).filter((k) => MOBILE_STEPS.includes(k));
      if (keys.length !== 1) { errors.push(`${where}.steps[${j}]: exactly one action among ${MOBILE_STEPS.join(", ")}`); return; }
      const v = s[keys[0]];
      if (keys[0] === "type" && (typeof v === "object" ? v?.text == null : v == null)) errors.push(`${where}.steps[${j}]: type needs a text (or {into, text})`);
      if (["tap", "long_press", "expect", "expect_gone", "scroll_to"].includes(keys[0]) && !(typeof v === "string" || v?.id || v?.text)) errors.push(`${where}.steps[${j}]: ${keys[0]} needs a visible text or {id}`);
    });
    flows.push(f);
  }
  if (flows.length && !m.app_id) errors.push("mobile.app_id is required to play flows (Android applicationId or iOS bundle identifier, e.g. com.example.app)");
  return { flows, errors, mobile: m };
}

// A flow of project.json as a Maestro flow file.
export function toMaestro(flow, appId) {
  const out = [`# Generated by shipwright from .quality/project.json › mobile.flows (${flow.id}). Edit the project file, not this one.`, `appId: ${appId}`, "---"];
  const steps = Object.keys(flow.steps[0]).includes("launch") ? flow.steps : [{ launch: { clear_state: true } }, ...flow.steps];
  let shot = 0;
  const snap = (name) => out.push(`- takeScreenshot: ${q(`${flow.id}-${String(++shot).padStart(2, "0")}-${String(name).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "step"}`)}`);
  for (const s of steps) {
    const [k] = Object.keys(s).filter((x) => MOBILE_STEPS.includes(x));
    const v = s[k];
    switch (k) {
      case "launch": out.push("- launchApp:", `    clearState: ${v === false || v?.clear_state === false ? "false" : "true"}`); break;
      case "tap": out.push(`- tapOn:${target(v)}`); break;
      case "long_press": out.push(`- longPressOn:${target(v)}`); break;
      case "type":
        if (typeof v === "object" && v.into) out.push(`- tapOn:${target(v.into)}`);
        out.push(`- inputText: ${q(typeof v === "object" ? v.text : v)}`); break;
      case "erase": out.push(typeof v === "number" ? `- eraseText: ${v}` : "- eraseText"); break;
      case "expect": out.push(`- assertVisible:${target(v)}`); break;
      case "expect_gone": out.push(`- assertNotVisible:${target(v)}`); break;
      case "wait_for": {
        const what = typeof v === "string" ? v : v.visible ?? v.text ?? v;
        out.push("- extendedWaitUntil:", `    visible:${typeof what === "string" ? ` ${q(what)}` : target(what, "      ")}`, `    timeout: ${Number(v?.timeout) || 10000}`); break;
      }
      case "screenshot": snap(v === true ? s.name || "screen" : v); continue;
      case "back": out.push("- back"); break;
      case "scroll_to": out.push("- scrollUntilVisible:", `    element:${typeof v === "string" ? ` ${q(v)}` : target(v, "      ")}`); break;
      case "swipe": out.push("- swipe:", `    direction: ${String(v).toUpperCase()}`); break;
      case "open_link": out.push(`- openLink: ${q(v)}`); break;
      case "offline": out.push(`- setAirplaneMode: ${v ? "enabled" : "disabled"}`); break;
      case "dark": out.push(`- setDarkMode: ${v ? "enabled" : "disabled"}`); break;
      case "hide_keyboard": out.push("- hideKeyboard"); break;
      case "press": out.push(`- pressKey: ${sel(v) ?? q("Enter")}`); break;
    }
    // A picture after each step that changes the screen, like the web flows; snapshot: false skips it.
    if (s.snapshot !== false && ["launch", "tap", "long_press", "type", "back", "scroll_to", "swipe", "open_link", "offline", "dark"].includes(k)) snap(s.name || `${k}-${typeof v === "string" ? v : v?.id || v?.text || ""}`);
  }
  return out.join("\n") + "\n";
}

export function writeMaestroFlows(project, root) {
  const { flows, errors, mobile } = validateMobile(project);
  if (errors.length) return { errors };
  const dir = join(root, ".maestro", "qp");
  mkdirSync(dir, { recursive: true });
  const files = flows.map((f) => { const p = join(dir, `${f.id}.yaml`); writeFileSync(p, toMaestro(f, mobile.app_id)); return relative(root, p).split("\\").join("/"); });
  return { files, effort: flows.map((f) => ({ id: f.id, name: f.name, steps: f.steps.length, actions: f.steps.filter((s) => COUNTED.has(Object.keys(s).find((k) => MOBILE_STEPS.includes(k)))).length })) };
}

// JUnit report written by `maestro test --format junit`.
export function parseJunit(xml) {
  const cases = [];
  const re = /<testcase\b([^>]*?)(\/>|>([\s\S]*?)<\/testcase>)/g;
  const attr = (s, n) => new RegExp(`\\b${n}="([^"]*)"`).exec(s)?.[1] ?? null;
  for (let m; (m = re.exec(xml));) {
    const body = m[3] || "";
    const fail = /<(failure|error)\b[^>]*?(?:message="([^"]*)")?[^>]*>([\s\S]*?)<\/\1>|<(failure|error)\b[^>]*message="([^"]*)"[^>]*\/>/.exec(body);
    cases.push({ name: attr(m[1], "name") || attr(m[1], "id"), seconds: Number(attr(m[1], "time")) || null, ok: !fail && !/status="ERROR"|status="FAILED"/i.test(m[1]),
      error: fail ? String(fail[2] || fail[5] || fail[3] || "").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&").trim().split("\n")[0].slice(0, 240) : undefined });
  }
  return cases;
}

export function maestroAvailable() {
  const r = spawnSync("maestro", ["--version"], { encoding: "utf8", shell: true, timeout: 60000 });
  return r.status === 0 ? { ok: true, version: (r.stdout || "").trim().split(/\r?\n/).pop() } : { ok: false };
}

export function playMobileFlows(project, { root, outDir, only = [] } = {}) {
  const written = writeMaestroFlows(project, root);
  if (written.errors) return { available: true, errors: written.errors };
  if (!written.files.length) return { available: true, errors: ["no mobile.flows in .quality/project.json: declare 2 to 5 key tasks of the app (see the mobile-app skill)"] };
  const files = only.length ? written.files.filter((f) => only.some((id) => f.endsWith(`/${id}.yaml`))) : written.files;
  const m = maestroAvailable();
  if (!m.ok) return { available: false, generated: written.files, effort: written.effort,
    hint: "Maestro is not installed. The flow files were written to .maestro/qp/. To play them: install Maestro (free CLI, needs Java 17+; ask the user first), start an Android emulator or an iOS simulator with the app installed, then run this command again." };
  const dir = join(outDir, "mobile");
  mkdirSync(dir, { recursive: true });
  const report = join(dir, "maestro.xml");
  const r = spawnSync("maestro", ["test", "--format", "junit", "--output", `"${report}"`, "--test-output-dir", `"${dir}"`, ...files.map((f) => `"${join(root, f)}"`)],
    { cwd: root, encoding: "utf8", shell: true, timeout: 30 * 60 * 1000, maxBuffer: 64 * 1024 * 1024 });
  if (!existsSync(report)) return { available: true, errors: [`Maestro wrote no report (exit ${r.status ?? "killed"}): ${`${r.stdout || ""}\n${r.stderr || ""}`.split(/\r?\n/).filter((l) => l.trim()).slice(-4).join(" | ").slice(0, 400)}. Is a device or emulator running with the app installed?`] };
  const cases = parseJunit(readFileSync(report, "utf8"));
  const shots = existsSync(dir) ? readdirSync(dir, { recursive: true }).filter((f) => /\.png$/i.test(String(f))).length : 0;
  return { available: true, tool: `Maestro ${m.version}`, flows: cases.map((c) => ({ ...c, ...(written.effort.find((e) => c.name?.includes(e.id)) || {}) })),
    summary: { flows: cases.length, completed: cases.filter((c) => c.ok).length, failed: cases.filter((c) => !c.ok).map((c) => `${c.name}: ${c.error || "failed"}`), screenshots: shots },
    report: relative(root, report).split("\\").join("/"), note: "Played on the device or emulator that was running. iOS needs macOS; say in the audit which platforms were played." };
}

