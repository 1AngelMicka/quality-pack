const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const level = (s) => (s == null ? "na" : s >= 7.5 ? "good" : s >= 6 ? "fair" : "poor");

function sparkline(history, areas, lang) {
  const pts = history.filter((h) => h.scores);
  if (pts.length < 2) return "";
  const W = 640, H = 160, P = 28;
  const x = (i) => P + (i * (W - 2 * P)) / (pts.length - 1);
  const y = (v) => H - P - (v / 10) * (H - 2 * P);
  const lines = Object.entries(areas).map(([k, a], n) => {
    const d = pts.map((h, i) => (h.scores[k]?.score == null ? null : `${x(i).toFixed(1)},${y(h.scores[k].score).toFixed(1)}`)).filter(Boolean);
    return `<polyline class="line l${n}" points="${d.join(" ")}"/>` + pts.map((h, i) => h.scores[k]?.score == null ? "" :
      `<circle class="dot l${n}" cx="${x(i).toFixed(1)}" cy="${y(h.scores[k].score).toFixed(1)}" r="3"><title>${esc(a.label[lang])} ${h.run}: ${h.scores[k].score}</title></circle>`).join("");
  }).join("");
  const grid = [0, 5, 10].map((v) => `<line class="grid" x1="${P}" x2="${W - P}" y1="${y(v)}" y2="${y(v)}"/><text class="axis" x="4" y="${y(v) + 4}">${v}</text>`).join("");
  const labels = [0, pts.length - 1].map((i) => `<text class="axis" x="${x(i)}" y="${H - 6}" text-anchor="${i ? "end" : "start"}">${esc(pts[i].run)}</text>`).join("");
  const legend = Object.values(areas).map((a, n) => `<span class="key"><i class="sw l${n}"></i>${esc(a.label[lang])}</span>`).join("");
  return `<figure class="history"><svg viewBox="0 0 ${W} ${H}" role="img" aria-label="${esc(T[lang].history)}">${grid}${lines}${labels}</svg><figcaption>${legend}</figcaption></figure>`;
}

function shot(path, alt, cls = "") {
  if (!path) return `<div class="noshot">—</div>`;
  const src = `../${path}`;
  return `<a href="${esc(src)}" target="_blank" rel="noopener"><img class="${cls}" loading="lazy" src="${esc(src)}" alt="${esc(alt)}"></a>`;
}

function stepMetrics(s, t) {
  if (!s) return "";
  if (!s.ok) return `<p class="err">${esc(s.error)}</p>`;
  const m = s.metrics || {};
  const bits = [];
  if (m.page_screens != null) bits.push(`${m.page_screens} ${t.pages}`);
  if (m.controls_rendered != null) bits.push(`${m.controls_rendered} ${t.controls}`);
  if (s.scrolled_screens) bits.push(`${s.scrolled_screens} ${t.scrolled}`);
  if (s.axe?.critical || s.axe?.serious) bits.push(`<b class="bad">${(s.axe.critical || 0) + (s.axe.serious || 0)} ${t.axe}</b>`);
  return `<p class="metrics">${bits.join(" · ")}${s.screenshot_full ? ` · <a href="../${esc(s.screenshot_full)}" target="_blank" rel="noopener">${t.full}</a>` : ""}</p>`;
}

// Over-budget lines in the report's language, rebuilt from the run's measures and the budgets.
function overBudget(r, budgets, t) {
  const s = r.summary;
  const val = { page_screens: s.max_page_screens, controls_rendered: s.max_controls_rendered, scroll_screens: s.scroll_screens, actions: s.actions };
  return Object.keys(val).filter((k) => { const b = r.budget?.[k] ?? budgets?.[k]?.[r.device]; return b != null && val[k] > b; })
    .map((k) => `${t.over[k].replace("{v}", val[k])} (${t.budget} ${r.budget?.[k] ?? budgets[k][r.device]})`);
}

function flowsSection(flows, t) {
  if (!flows?.flows?.length) return `<p class="note">${t.noFlows}</p>`;
  return flows.flows.map((f) => {
    const runs = f.runs.filter((r) => r.scheme !== "dark");
    const byDevice = Object.fromEntries(runs.map((r) => [r.device, r]));
    const head = runs.map((r) => {
      const s = r.summary;
      const facts = [`${s.actions} ${t.actions}`, ...(s.klm_seconds != null ? [`≈ ${s.klm_seconds} s (KLM)`] : []), `${s.max_page_screens} ${t.pages}`, `${s.max_controls_rendered} ${t.controls}`, `${s.scroll_screens} ${t.scrolled}`];
      if (s.preview_visible_while_adjusting != null) facts.push(`${t.preview} ${Math.round(s.preview_visible_while_adjusting * 100)} %`);
      if (s.primary_visible != null) facts.push(`${t.primary} : ${s.primary_visible ? t.yes : t.no}`);
      if (s.primary_in_thumb_zone != null) facts.push(`${t.thumb} : ${s.primary_in_thumb_zone ? t.yes : t.no}`);
      return `<div class="run"><h4>${r.device === "mobile" ? t.phone : t.desktop} <span class="pill ${r.completed ? "good" : "poor"}">${r.completed ? t.completed : `${t.failed} ${r.failed_step}`}</span></h4>
        <p class="facts">${facts.join(" · ")}</p>
        ${overBudget(r, flows.budgets, t).length ? `<p class="pill poor">${t.overBudget}</p><ul class="budget">${overBudget(r, flows.budgets, t).map((o) => `<li>${esc(o)}</li>`).join("")}</ul>` : `<p class="pill good">${t.inBudget}</p>`}</div>`;
    }).join("");
    const count = Math.max(...runs.map((r) => r.steps.length));
    const rows = Array.from({ length: count }, (_, i) => {
      const m = byDevice.mobile?.steps[i], d = byDevice.desktop?.steps[i];
      const s = m || d;
      return `<div class="step"><div class="stepname"><b>${t.step} ${i + 1}</b> ${esc(s?.name)}${s?.decision ? ` <span class="pill">${t.decision}</span>` : ""}</div>
        <div class="cell phone">${m ? shot(m.screenshot, `${f.name}, ${t.phone}, ${t.step} ${i + 1}`, "ph") + stepMetrics(m, t) : ""}</div>
        <div class="cell desk">${d ? shot(d.screenshot, `${f.name}, ${t.desktop}, ${t.step} ${i + 1}`, "dk") + stepMetrics(d, t) : ""}</div></div>`;
    }).join("");
    return `<article class="flow" id="flow-${esc(f.id)}"><h3>${esc(f.name)} <code>${esc(f.id)}</code></h3><div class="runs">${head}</div>
      <div class="steps"><div class="step headrow"><div></div><div>${t.phone}</div><div>${t.desktop}</div></div>${rows}</div></article>`;
  }).join("");
}

function issueTable(rows, t, lang, areas) {
  if (!rows.length) return `<p>${t.none}</p>`;
  return `<table><thead><tr><th>ID</th><th></th><th>${t.fix}</th></tr></thead><tbody>${rows.map((i) =>
    `<tr><td><code>${esc(i.id)}</code><br><span class="pill ${i.severity === "blocker" ? "poor" : i.severity === "major" ? "fair" : ""}">${t.sev[i.severity]}</span></td>
     <td>${esc(i.label[lang])}<br><small>${esc(areas[i.area]?.label[lang] || "")}${i.challenged_from ? ` · ${t.challenged}` : ""}</small></td><td>${esc(i.fix || "—")}</td></tr>`).join("")}</tbody></table>`;
}

