#!/usr/bin/env python3
"""Build everything generated from the YAML sources. Run after any change:

  python tools/build.py

It validates the referential, then writes:
  - docs/fr/REFERENTIEL.md, docs/en/REFERENTIAL.md
  - plugins/core/referential/referential.json   (read by the Node scripts at runtime)
  - plugins/<stack>/stack.json                   (read by the Node scripts at runtime)
  - plugins/core/skills/build-<group>/SKILL.md   (one build skill per group)
  - plugins/<stack>/skills/<stack>-rules/SKILL.md
  - .claude-plugin/marketplace.json and every plugin.json (version from VERSION)
Generated files must not be edited by hand; CI fails if they are out of date.
"""
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import referential as R  # noqa: E402

ROOT = R.ROOT
REF = R.REF
VERSION = (ROOT / "VERSION").read_text().strip()
AUTHOR = {"name": "Micka", "url": "https://github.com/1AngelMicka"}
REPO = "https://github.com/1AngelMicka/quality-pack"
GEN = "<!-- Generated by tools/build.py from the referential YAML. Do not edit by hand. -->"

PLUGINS = {
    "core": {"name": "qp", "description": "Quality pack core: 27-domain referential, scoring, build skills, /qp:kickoff, /qp:audit, /qp:fix. Socle du pack qualité : référentiel 27 domaines, notation, skills de construction, /qp:kickoff, /qp:audit, /qp:fix."},
    "stack-nextjs": {"name": "qp-nextjs", "description": "Quality pack module for Next.js, React, TypeScript and Tailwind. Module Next.js / React / TypeScript / Tailwind du pack qualité."},
    "stack-node-api": {"name": "qp-node-api", "description": "Quality pack module for Node APIs: Fastify or Express, Prisma, PostgreSQL, Redis, Socket.io. Module API Node du pack qualité."},
    "infra-vps": {"name": "qp-vps", "description": "Quality pack module for self-hosted VPS: Docker Compose, PM2, Nginx or CloudPanel, backups. Module VPS auto-hébergé du pack qualité."},
}

GROUP_TRIGGERS = {
    "product-experience": "Use when defining a product or feature, writing a spec, designing a user flow, building a screen that shows data, a form, empty, loading or error states, writing interface copy, help pages or support. FR: produit, spec, parcours, formulaire, état vide, message d'erreur, textes, aide, support.",
    "design": "Use when building or styling UI: components, design tokens, layout, responsive behaviour, animation, accessibility (contrast, keyboard, screen readers), browser compatibility, or when a page looks generic, templated or AI-made. FR: interface, design, responsive, accessibilité, contraste, animation, rendu générique.",
    "security-data": "Use when touching authentication, sessions, permissions, user input, secrets, file uploads, HTTP headers, personal data, cookies and consent, database schema and migrations, legal notices or licences. FR: sécurité, authentification, validation, secrets, RGPD, cookies, base de données, migrations, mentions légales, licences.",
    "reliability-quality": "Use when writing or reviewing code for error handling, timeouts, retries, edge cases, tests (unit, integration, end-to-end), typing, linting, debug leftovers or the README. FR: gestion d'erreurs, cas limites, tests, typage, lint, logs de débogage.",
    "performance-seo": "Use when working on speed (Core Web Vitals, images, fonts, bundle size, database queries, caching), SEO and metadata (titles, descriptions, OpenGraph, sitemap, robots, favicons) or load and scaling. FR: performance, images, cache, SEO, métadonnées, OpenGraph, montée en charge.",
    "integrations-payments": "Use when integrating an external API, webhooks, transactional or marketing emails, payments, subscriptions or cancellation (Stripe and similar), or any usage-billed service. FR: API externe, webhook, email, paiement, abonnement, résiliation, coûts.",
    "operations": "Use when configuring servers, Docker, PM2, Nginx, HTTPS, CI, deployment and rollback, monitoring, alerts, logs or backups and restores. FR: serveur, déploiement, retour arrière, monitoring, alertes, logs, sauvegardes, restauration.",
}


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def flag_en(f, scoring):
    return R.flag_label(f, scoring, "en")


def build_json(scoring, checks, groups):
    slop = yaml.safe_load((REF / "slop-words.yaml").read_text(encoding="utf-8"))
    data = {"version": VERSION, "scoring": scoring["scoring"], "flags": scoring["flags"],
            "derived_flags": scoring["derived_flags"], "profiles": scoring["profiles"],
            "checks": checks, "slop_words": slop, "groups": groups}
    write(REF / "referential.json", json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    for sf in sorted((ROOT / "plugins").glob("*/stack.yaml")):
        st = yaml.safe_load(sf.read_text(encoding="utf-8"))
        st["qp_stack"] = True
        st["plugin"] = PLUGINS[sf.parent.name]["name"]
        write(sf.parent / "stack.json", json.dumps(st, ensure_ascii=False, indent=1) + "\n")


def build_group_skills(scoring, groups):
    sev = {"blocker": "BLOCKER", "major": "major", "minor": "minor"}
    for g in groups:
        names = ", ".join(d["label"]["en"] for d in g["domains"])
        desc = f"Quality pack build rules for {g['label']['en']} ({names}). {GROUP_TRIGGERS[g['group']]}"
        L = ["---", f"name: build-{g['group']}", f"description: {json.dumps(desc, ensure_ascii=False)}", "---", GEN, "",
             f"# {g['label']['en']}: build rules", "",
             "Apply these rules while you build. Domains or criteria whose `applies_if` flags are false in "
             "`.quality/project.json` do not apply to this project. Before you call a task done, check your work "
             "against the criteria of the domains you touched: each one must be true and verifiable.", "",
             "If a stack module of the quality pack is installed (qp-nextjs, qp-node-api, qp-vps), its rules skill "
             "adds stack-specific rules on top of these.", ""]
        for d in g["domains"]:
            L += [f"## {d['label']['en']} ({d['code']})", "", d["summary"]["en"]]
            if d.get("applies_if"):
                L += ["", "Applies when: " + "; ".join(flag_en(f, scoring) for f in d["applies_if"]) + "."]
            L += ["", "Rules:", ""] + [f"- {r['en']}" for r in d.get("build", [])]
            L += ["", "Done means:", ""]
            for c in d["criteria"]:
                cond = f" (only if: {', '.join(c['applies_if'])})" if c.get("applies_if") else ""
                L.append(f"- [{sev[c['severity']]}] {c['id']}: {c['label']['en']}{cond}. Check: {c['verify']['en']}")
            L.append("")
        write(ROOT / "plugins" / "core" / "skills" / f"build-{g['group']}" / "SKILL.md", "\n".join(L))


def build_stack_skills():
    for sf in sorted((ROOT / "plugins").glob("*/stack.yaml")):
        st = yaml.safe_load(sf.read_text(encoding="utf-8"))
        name = f"{st['stack']}-rules"
        desc = (f"Quality pack rules and check commands for {st['label']['en']}. Use when writing, reviewing or "
                f"auditing code in a project that uses this stack. FR : règles et commandes de vérification pour {st['label']['fr']}.")
        L = ["---", f"name: {name}", f"description: {json.dumps(desc, ensure_ascii=False)}", "---", GEN, "",
             f"# {st['label']['en']}", "", "These rules add to the core build skills of the quality pack.", "", "## Rules", ""]
        L += [f"- {r['en']}" for r in st.get("rules", [])]
        L += ["", "## Check commands", "",
              "Used by `/qp:audit`. `{pm}` is the project's package manager, `{url}` the app URL, `{host}` its host name.", "",
              "| Check | Command | Passes if |", "| --- | --- | --- |"]
        for k, v in st.get("checks", {}).items():
            cmd = v["run"].replace("|", "\\|")
            L.append(f"| {k} | `{cmd}` | {v['pass_if']} |")
        write(sf.parent / "skills" / name / "SKILL.md", "\n".join(L) + "\n")


def build_manifests():
    mk = {"name": "quality-pack",
          "description": "Build and audit web projects across 27 quality domains, with scoring. Construire et auditer des projets web sur 27 domaines qualité, avec notation.",
          "owner": AUTHOR, "plugins": []}
    for d, p in PLUGINS.items():
        pj = {"name": p["name"], "description": p["description"], "version": VERSION, "author": AUTHOR,
              "license": "MIT", "homepage": REPO, "repository": REPO, "keywords": ["quality", "audit", "security", "accessibility", "seo", "qualité"]}
        if d != "core":
            pj["dependencies"] = ["qp"]
        write(ROOT / "plugins" / d / ".claude-plugin" / "plugin.json", json.dumps(pj, ensure_ascii=False, indent=2) + "\n")
        mk["plugins"].append({"name": p["name"], "description": p["description"], "version": VERSION,
                              "source": f"./plugins/{d}", "author": AUTHOR})
    write(ROOT / ".claude-plugin" / "marketplace.json", json.dumps(mk, ensure_ascii=False, indent=2) + "\n")


def build_site():
    import shutil
    site = ROOT / "site"
    shutil.copyfile(REF / "referential.json", site / "referential.json")
    shutil.copyfile(ROOT / "llms.txt", site / "llms.txt")
    print("wrote site/referential.json, site/llms.txt")


def main():
    errors, nd, nc = R.validate()
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    print(f"OK: {nd} domains, {nc} criteria")
    scoring, checks, groups = R.load()
    R.docs()
    build_json(scoring, checks, groups)
    build_group_skills(scoring, groups)
    build_stack_skills()
    build_manifests()
    build_site()


if __name__ == "__main__":
    main()
